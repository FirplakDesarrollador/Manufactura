    ('CEFI', 'CEFI',             0.13, 0.95, 3),
    ('FV',   'Fibra de Vidrio',  0.03, 0.35, 4),
    ('RTM',  'Quarzstone (RTM)', 0.02, 0.70, 5)
ON CONFLICT (codigo) DO UPDATE
SET nombre = EXCLUDED.nombre, peso = EXCLUDED.peso, meta = EXCLUDED.meta, orden = EXCLUDED.orden, updated_at = now();

CREATE TABLE IF NOT EXISTS calidad_ifi_diaria (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    fecha           date NOT NULL,
    planta          text NOT NULL REFERENCES calidad_ifi_plantas(codigo),
    calidad         numeric(6,4) NOT NULL CHECK (calidad >= 0 AND calidad <= 1),
    revisadas       int,
    buenas          int,
    fuente          text NOT NULL CHECK (fuente IN ('supabase_ms', 'sharepoint_fv', 'manual', 'excel')),
    registrado_por  text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (fecha, planta)
);

CREATE TABLE IF NOT EXISTS calidad_ifi_mensual (
    anio        int NOT NULL,
    mes         int NOT NULL CHECK (mes BETWEEN 1 AND 12),
    planta      text NOT NULL REFERENCES calidad_ifi_plantas(codigo),
    calidad     numeric(6,4) CHECK (calidad IS NULL OR (calidad >= 0 AND calidad <= 1)),
    fuente      text NOT NULL,
    dudoso      boolean NOT NULL DEFAULT false,
    nota        text,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (anio, mes, planta)
);

-- Seguridad: lectura para usuarios con sesión; escritura controlada por la app (rol Calidad/Admin)
ALTER TABLE calidad_ifi_plantas ENABLE ROW LEVEL SECURITY;
ALTER TABLE calidad_ifi_diaria  ENABLE ROW LEVEL SECURITY;
ALTER TABLE calidad_ifi_mensual ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS calidad_ifi_plantas_select ON calidad_ifi_plantas;
CREATE POLICY calidad_ifi_plantas_select ON calidad_ifi_plantas FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS calidad_ifi_diaria_select ON calidad_ifi_diaria;
CREATE POLICY calidad_ifi_diaria_select ON calidad_ifi_diaria FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS calidad_ifi_diaria_write ON calidad_ifi_diaria;
CREATE POLICY calidad_ifi_diaria_write ON calidad_ifi_diaria FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS calidad_ifi_mensual_select ON calidad_ifi_mensual;
CREATE POLICY calidad_ifi_mensual_select ON calidad_ifi_mensual FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS calidad_ifi_mensual_write ON calidad_ifi_mensual;
CREATE POLICY calidad_ifi_mensual_write ON calidad_ifi_mensual FOR ALL TO authenticated USING (true) WITH CHECK (true);

