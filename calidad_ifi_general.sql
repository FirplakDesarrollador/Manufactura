-- =====================================================================
-- Calidad General Plantas - IFI (MS, MBL, CEFI, FV, RTM)
--
-- Resultado de un día = Σ peso_efectivo × mín(calidad / meta, 100%)
--   peso_efectivo = peso de la planta ÷ suma de pesos de las plantas con dato ese día
--   (si solo reporta una planta, esa planta pesa 100%).
-- Resultado del mes = promedio de los resultados diarios.
--
-- Tablas:
--   calidad_ifi_plantas  : peso y meta vigentes por planta
--   calidad_ifi_diaria   : calidad diaria por planta (MS/FV automáticos, MBL/CEFI/RTM digitados)
--   calidad_ifi_mensual  : histórico mensual por planta (Excel PROMEDIO IFI PLANTAS + SharePoint FV)
--
-- Ejecutar UNA vez en el SQL Editor de Supabase. Todo va en una transacción.
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS calidad_ifi_plantas (
    codigo      text PRIMARY KEY,
    nombre      text NOT NULL,
    peso        numeric(6,4) NOT NULL CHECK (peso >= 0 AND peso <= 1),
    meta        numeric(6,4) NOT NULL CHECK (meta > 0 AND meta <= 1),
    orden       int NOT NULL,
    activa      boolean NOT NULL DEFAULT true,
    updated_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO calidad_ifi_plantas (codigo, nombre, peso, meta, orden) VALUES
