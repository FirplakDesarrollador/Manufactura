-- =====================================================================
-- Control de Piso Superficies (RTM / Inyección)
-- Órdenes de fabricación de las familias RTM y RTMM de SAP (campo U_Familia del artículo). Sin moldes.
-- Flujo de cada unidad: Programado (sin pulir) → Pulido → Digitado (pendiente de digitar = estado 'Pulido')
--                        → Tránsito (digitado registrado) → CEDI.  Desde Pulido también a Reparación;
--                        desde Reparación: a Digitado, Saldo o Destrucción.
-- Se registra por cantidad (ej. 10 de 24); por dentro queda una fila por unidad (trazabilidad), como en FV.
-- Ejecutar UNA vez en Supabase. Se puede volver a ejecutar sin perder datos.
-- =====================================================================

-- 1) Órdenes de fabricación (las carga /api/sap/ordenes-liberadas desde SAP)
create table if not exists public.ordenes_fabricacion_rtm (
    id bigint generated by default as identity primary key,
    orden_fabricacion text not null unique,
    numero_pedido text,
    producto_sku text,
    producto_descripcion text,
    familia text,                              -- RTM | RTMM (U_Familia en SAP)
    cantidad numeric not null default 1,
    cantidad_completada_sap numeric not null default 0,
    cliente text,
    comentario text,
    fecha_entrega_estimada text,
    fecha_ideal_produccion text,
    fecha_entrega_lote text,                   -- fechas del Semáforo (T, real liberación, W, AF)
    fecha_real_liberacion text,
    fecha_ideal_entrega_produccion text,
    fecha_prometida_entrega text,
    fechas_semaforo_actualizadas timestamptz,
    pendiente boolean not null default true,
    fecha_entrega_real timestamptz,
    modificado_por text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- 2) Una fila por unidad registrada (trazabilidad). Programado = cantidad − unidades registradas.
create table if not exists public.trazabilidad_rtm (
    id bigint generated by default as identity primary key,
    registrer text not null unique,
    orden_fabricacion_id bigint not null references public.ordenes_fabricacion_rtm (id) on delete cascade,
    estado text not null check (estado in ('Pulido', 'Reparacion', 'Transito', 'Cedi', 'Saldo', 'Destruccion')),
    pulido_fecha timestamptz, pulido_user_id bigint,
    reparacion_fecha timestamptz, reparacion_user_id bigint,
    digitado_fecha timestamptz, digitado_user_id bigint,
    cedi_fecha timestamptz, cedi_user_id bigint,
    saldo_fecha timestamptz, saldo_user_id bigint,
    destruccion_fecha timestamptz, destruccion_user_id bigint,
    created_at timestamptz not null default now()
);
create index if not exists trazabilidad_rtm_orden_idx on public.trazabilidad_rtm (orden_fabricacion_id, estado);
create index if not exists trazabilidad_rtm_estado_idx on public.trazabilidad_rtm (estado);

-- 3) Historial de movimientos (registros y movimientos manuales de Administración), solo agregar
create table if not exists public.movimientos_rtm (
    id bigint generated always as identity primary key,
    created_at timestamptz not null default now(),
    usuario_email text not null,
    origen text not null,                      -- pulido | reparacion | digitado | cedi | administracion
    accion text not null,                      -- registrar | mover | devolver_programado
    orden_fabricacion text,
    estado_antes text,
    estado_despues text,
    cantidad integer not null default 1,
    detalle jsonb
);
create index if not exists movimientos_rtm_of_idx on public.movimientos_rtm (orden_fabricacion, created_at desc);

-- 4) Parámetros por producto (kg por unidad para el indicador de kilos)
create table if not exists public.productos_rtm_parametros (
    producto_sku text primary key,
    kg_unidad numeric,
    actualizado_por text,
    updated_at timestamptz not null default now()
);

-- 5) Caché de la familia de cada artículo de SAP (U_Familia): la carga de órdenes no la consulta cada vez
create table if not exists public.sap_items_familia (
    item_code text primary key,
    familia text,
    actualizado timestamptz not null default now()
);

-- 6) Traslados de Superficies: misma estructura de traslados_of_fv
create table if not exists public.traslados_of_rtm (like public.traslados_of_fv including defaults);
do $$
begin
  if not exists (select 1 from pg_constraint where conrelid = 'public.traslados_of_rtm'::regclass and contype in ('p', 'u')) then
    alter table public.traslados_of_rtm add constraint traslados_of_rtm_of_key unique (orden_fabricacion);
  end if;
end $$;

-- 7) Vista de órdenes pendientes con el conteo de unidades por proceso
create or replace view public.ordenes_fabricacion_rtm_v as
select o.*,
       greatest(o.cantidad - coalesce(c.total, 0), 0)::int as programado,
       coalesce(c.pulido, 0)::int as pulido,
       coalesce(c.reparacion, 0)::int as reparacion,
       coalesce(c.transito, 0)::int as transito,
       coalesce(c.cedi, 0)::int as cedi,
       coalesce(c.saldo, 0)::int as saldo,
       coalesce(c.destruccion, 0)::int as destruccion,
       coalesce(c.total, 0)::int as registradas
  from public.ordenes_fabricacion_rtm o
  left join lateral (
      select count(*) as total,
             count(*) filter (where t.estado = 'Pulido') as pulido,
             count(*) filter (where t.estado = 'Reparacion') as reparacion,
             count(*) filter (where t.estado = 'Transito') as transito,
             count(*) filter (where t.estado = 'Cedi') as cedi,
             count(*) filter (where t.estado = 'Saldo') as saldo,
             count(*) filter (where t.estado = 'Destruccion') as destruccion
        from public.trazabilidad_rtm t where t.orden_fabricacion_id = o.id
  ) c on true
 where o.pendiente;

-- 8) Permisos
--    La carga de órdenes, la caché de familias y los traslados corren en el servidor sin sesión (anon), como en FV.
do $$
declare t text;
begin
  foreach t in array array['ordenes_fabricacion_rtm', 'trazabilidad_rtm', 'movimientos_rtm', 'productos_rtm_parametros', 'sap_items_familia', 'traslados_of_rtm'] loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

do $$
declare t text; roles text;
begin
  foreach t in array array['ordenes_fabricacion_rtm', 'trazabilidad_rtm', 'productos_rtm_parametros', 'sap_items_familia', 'traslados_of_rtm'] loop
    roles := case when t in ('ordenes_fabricacion_rtm', 'sap_items_familia', 'traslados_of_rtm') then 'anon, authenticated' else 'authenticated' end;
    if not exists (select 1 from pg_policies where tablename = t and policyname = t || '_select') then
      execute format('create policy %I on public.%I for select to %s using (true)', t || '_select', t, roles);
    end if;
    if not exists (select 1 from pg_policies where tablename = t and policyname = t || '_insert') then
      execute format('create policy %I on public.%I for insert to %s with check (true)', t || '_insert', t, roles);
    end if;
    if not exists (select 1 from pg_policies where tablename = t and policyname = t || '_update') then
      execute format('create policy %I on public.%I for update to %s using (true) with check (true)', t || '_update', t, roles);
    end if;
    if not exists (select 1 from pg_policies where tablename = t and policyname = t || '_delete') then
      execute format('create policy %I on public.%I for delete to %s using (true)', t || '_delete', t, roles);
    end if;
  end loop;
end $$;
