-- Ejecutar UNA vez en el SQL Editor de Supabase.
-- Solo crea la tabla y sus permisos: no borra ni modifica datos existentes.
-- Lo que se jala de Control de Piso y Calidad queda congelado en "datos"
-- tal como se envió, junto con lo que diligenció el supervisor.
-- =====================================================================

create table if not exists public.informe_turno_ms (
  id bigint generated by default as identity primary key,
  fecha date not null,                       -- día del turno
  usuario_uuid uuid,
  usuario_email text,
  datos jsonb not null default '{}'::jsonb,  -- campos manuales + datos automáticos
  texto text,                                -- informe tal como se envió por WhatsApp
  activo boolean not null default true,      -- anular = activo false (no se borra)
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists informe_turno_ms_fecha_idx
  on public.informe_turno_ms (fecha desc) where activo;

alter table public.informe_turno_ms enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where tablename = 'informe_turno_ms' and policyname = 'itm_select_autenticados') then
    create policy "itm_select_autenticados" on public.informe_turno_ms
      for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'informe_turno_ms' and policyname = 'itm_insert_autenticados') then
    create policy "itm_insert_autenticados" on public.informe_turno_ms
      for insert to authenticated with check (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'informe_turno_ms' and policyname = 'itm_update_autenticados') then
    create policy "itm_update_autenticados" on public.informe_turno_ms
      for update to authenticated using (true) with check (true);
  end if;
end $$;

notify pgrst, 'reload schema';
