-- =====================================================================
-- Esquema de personal de las plantas
-- Ejecutar UNA vez en el SQL Editor de Supabase (Manufactura).
-- Solo crea tablas, índices y permisos: no borra ni modifica datos.
-- No hay tabla de personal: las personas se leen siempre de Talento Humano
-- (tabla empleados). Aquí solo se guarda el id de TH y dónde está ubicada
-- cada persona dentro del esquema; nombre, cargo y estado vienen de TH.
-- "Quitar" en la app pone activo = false: nunca se borra un registro.
-- =====================================================================

-- Planta (MS, FV, MBL…) con sus objetivos del presupuesto
create table if not exists public.esquema_plantas (
  id bigint generated by default as identity primary key,
  codigo text not null unique,                 -- MS, FV, QZ, MBL, CEFI…
  nombre text not null,
  planta_th text,                              -- valor de "planta" en Talento Humano para listar su personal
  objetivo_fte numeric,                        -- personas objetivo (FTE) del presupuesto
  objetivo_piezas integer,                     -- piezas día del presupuesto
  nota text,
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Secciones dentro de la planta (Óvalo 1, Óvalo 2, CEFI…)
create table if not exists public.esquema_secciones (
  id bigint generated by default as identity primary key,
  planta_id bigint not null references public.esquema_plantas(id),
  nombre text not null,
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Turnos (columnas del esquema) con su horario
create table if not exists public.esquema_turnos (
  id bigint generated by default as identity primary key,
  planta_id bigint not null references public.esquema_plantas(id),
  nombre text not null,
  horario text,
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Puestos (filas del esquema). Un puesto con varios cupos se repite como en el Excel
create table if not exists public.esquema_puestos (
  id bigint generated by default as identity primary key,
  planta_id bigint not null references public.esquema_plantas(id),
  seccion_id bigint references public.esquema_secciones(id),
  nombre text not null,
  critico boolean not null default false,      -- puesto o cargo crítico
  cuenta_fte boolean not null default true,    -- false para supervisores: no suman al real
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Quién ocupa cada puesto en cada turno (una celda del esquema)
create table if not exists public.esquema_asignaciones (
  id bigint generated by default as identity primary key,
  puesto_id bigint not null references public.esquema_puestos(id),
  turno_id bigint not null references public.esquema_turnos(id),
  empleado_id bigint,                          -- id de la persona en Talento Humano (null solo en vacantes)
  estado text not null default 'ocupado' check (estado in ('ocupado', 'vacante', 'vacante_no_activa')),
  nuevo boolean not null default false,
  novedad text,                                -- novedad de la persona en ese puesto (amarillo en el Excel)
  activo boolean not null default true,
  usuario_email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint esquema_asignaciones_ocupado_con_persona check (estado <> 'ocupado' or empleado_id is not null)
);

-- Una sola asignación vigente por celda (puesto × turno)
create unique index if not exists esquema_asignaciones_celda_uidx
  on public.esquema_asignaciones (puesto_id, turno_id) where activo;

-- Personal con novedades que está fuera del esquema (incapacidades largas, apoyo a otra planta…)
create table if not exists public.esquema_novedades (
  id bigint generated by default as identity primary key,
  planta_id bigint not null references public.esquema_plantas(id),
  empleado_id bigint not null,                 -- id de la persona en Talento Humano
  observacion text,
  cuenta_fte boolean not null default true,    -- si suma al personal real de la planta
  activo boolean not null default true,
  usuario_email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Qué se cambió, quién y cuándo
create table if not exists public.esquema_historial (
  id bigint generated by default as identity primary key,
  planta_id bigint references public.esquema_plantas(id),
  accion text not null,
  detalle text,
  usuario_email text,
  created_at timestamptz not null default now()
);

create index if not exists esquema_secciones_planta_idx on public.esquema_secciones (planta_id) where activo;
create index if not exists esquema_turnos_planta_idx on public.esquema_turnos (planta_id) where activo;
create index if not exists esquema_puestos_planta_idx on public.esquema_puestos (planta_id) where activo;
create index if not exists esquema_novedades_planta_idx on public.esquema_novedades (planta_id) where activo;
create index if not exists esquema_historial_planta_idx on public.esquema_historial (planta_id, created_at desc);

-- Seguridad por filas (RLS) en todas las tablas del esquema
alter table public.esquema_plantas enable row level security;
alter table public.esquema_secciones enable row level security;
alter table public.esquema_turnos enable row level security;
alter table public.esquema_puestos enable row level security;
alter table public.esquema_asignaciones enable row level security;
alter table public.esquema_novedades enable row level security;
alter table public.esquema_historial enable row level security;

-- Permisos: usuarios autenticados leen, crean y actualizan. No hay permiso de borrar.
-- Quién puede editar (jefes y coordinadores) lo controla la app.
do $$
declare
  t text;
begin
  foreach t in array array['esquema_plantas', 'esquema_secciones', 'esquema_turnos', 'esquema_puestos',
                           'esquema_asignaciones', 'esquema_novedades', 'esquema_historial']
  loop
    if not exists (select 1 from pg_policies where tablename = t and policyname = t || '_select') then
      execute format('create policy %I on public.%I for select to authenticated using (true)', t || '_select', t);
    end if;
    if not exists (select 1 from pg_policies where tablename = t and policyname = t || '_insert') then
      execute format('create policy %I on public.%I for insert to authenticated with check (true)', t || '_insert', t);
    end if;
    if t <> 'esquema_historial' and not exists (select 1 from pg_policies where tablename = t and policyname = t || '_update') then
      execute format('create policy %I on public.%I for update to authenticated using (true) with check (true)', t || '_update', t);
    end if;
  end loop;
end $$;

notify pgrst, 'reload schema';
