-- =====================================================================
-- Módulo: Planos (Control de Piso Fibra de vidrio)
-- Ejecutar UNA vez en el SQL Editor del proyecto Supabase principal
-- (el mismo de NEXT_PUBLIC_SUPABASE_URL).
-- Solo crea la tabla, el bucket y los permisos: no borra ni modifica datos.
-- Un plano = un PDF por bañera y proceso. Al reemplazarlo, el anterior queda
-- con activo = false (historial de versiones). Los PDF del bucket no se borran.
-- =====================================================================

-- 1. Tabla de planos
create table if not exists public.fibra_planos (
  id bigint generated by default as identity primary key,
  banera text not null,                      -- bañera (descripción del producto)
  proceso text not null                     -- ojo: 'cantoneras' = Aplicación de masilla y 'masilla' = Cantoneras (ver lib/fibra-planos.ts)
    check (proceso in ('cantoneras', 'soldadura', 'masilla', 'pulido', 'ensamble', 'huacal')),  -- 'soldadura' se muestra como Herrajes
  pdf_path text not null,                    -- ruta en el bucket fibra-planos
  nombre_archivo text,                       -- nombre original del PDF
  version integer not null default 1,
  observacion text,
  activo boolean not null default true,      -- quitar / reemplazar = activo false (no se borra)
  usuario_email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Un solo plano vigente por bañera y proceso
create unique index if not exists fibra_planos_vigente_uidx
  on public.fibra_planos (lower(banera), proceso) where activo;

alter table public.fibra_planos enable row level security;

drop policy if exists "fibra_planos_select" on public.fibra_planos;
create policy "fibra_planos_select" on public.fibra_planos
  for select to authenticated using (true);

drop policy if exists "fibra_planos_insert" on public.fibra_planos;
create policy "fibra_planos_insert" on public.fibra_planos
  for insert to authenticated with check (true);

drop policy if exists "fibra_planos_update" on public.fibra_planos;
create policy "fibra_planos_update" on public.fibra_planos
  for update to authenticated using (true) with check (true);

-- 2. Bucket privado para los PDF (hasta 30 MB por plano)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fibra-planos', 'fibra-planos', false, 31457280, array['application/pdf'])
on conflict (id) do nothing;

drop policy if exists "fibra_planos_storage_select" on storage.objects;
create policy "fibra_planos_storage_select" on storage.objects
  for select to authenticated using (bucket_id = 'fibra-planos');

drop policy if exists "fibra_planos_storage_insert" on storage.objects;
create policy "fibra_planos_storage_insert" on storage.objects
  for insert to authenticated with check (bucket_id = 'fibra-planos');

notify pgrst, 'reload schema';
