-- =====================================================================
-- Productividad de las plantas (reemplaza el Excel "Nivel de productividad" y su Power BI)
-- Ejecutar UNA vez en el SQL Editor de Supabase. Solo crea tablas y permisos: no borra datos.
-- Después se carga el histórico con los archivos de datos-locales/productividad_historico (en orden).
--
--   prod_dia_planta       una fila por día y planta (equivale a BD_MS, BD_FV, BD_MBL, BD_CEFI, BD_RTM)
--   prod_paros            paros por día (equivale a BD_PAROS)
--   prod_plantas_activas  excepciones de plantas activas por día (columna PLANTAS ACTIVAS de BD_FPK)
--   prod_parametros       pesos por planta, inicio de MS en kilos, objetivos de pérdidas
-- El indicador general FIRPLAK (BD_FPK) no se guarda: la app lo calcula con la misma fórmula ponderada.
-- Porcentajes guardados como fracción (0,956 = 95,6 %).
-- =====================================================================

create table if not exists public.prod_dia_planta (
  fecha            date not null,
  planta           text not null check (planta in ('MS', 'MBL', 'CEFI', 'RTM', 'FV')),
  tiempo_min       numeric,          -- tiempo laborado / real de producción (min)
  mo_teorica       numeric,          -- mano de obra teórica
  mo_real          numeric,          -- mano de obra real
  obj_piezas       numeric,          -- objetivo de piezas del día
  real_piezas      numeric,          -- piezas que miden la productividad (MS acabado, FV acabado conversión, MBL taladro, CEFI empaque, RTM acabado)
  pct_prod_piezas  numeric,          -- real / objetivo
  obj_prod         numeric,          -- objetivo de productividad (0,9)
  obj_phh          numeric,          -- piezas hora hombre objetivo
  real_phh         numeric,
  prod_phh         numeric,          -- real / objetivo PHH
  kg_objetivo      numeric,          -- MS
  kg_real          numeric,          -- MS: kg entregados al CEDI
  pct_prod_kg      numeric,          -- MS
  kghh_real        numeric,          -- MS
  kghh_objetivo    numeric,          -- MS
  pct_prod_kghh    numeric,          -- MS
  -- Minutos de pérdida del día por familia (paros REFLEJADO) y averías reales (todos los paros de avería).
  -- Se guardan con el día: el histórico trae los del Excel tal cual (algunos días se escribieron a mano)
  -- y la app los calcula de los paros al registrar.
  min_funcional    numeric not null default 0,
  min_inducido     numeric not null default 0,
  min_explotacion  numeric not null default 0,
  min_averia       numeric not null default 0,
  min_averia_real  numeric not null default 0,
  paros_averia_real numeric not null default 0,
  detalle          jsonb not null default '{}'::jsonb,   -- todas las demás columnas de la planta (corte, enchape, pintura, líneas…)
  origen           text not null default 'app',          -- excel_historico | app | informe_turno
  registrado_por   text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  primary key (fecha, planta)
);
create index if not exists prod_dia_planta_planta_fecha_idx on public.prod_dia_planta (planta, fecha desc);

create table if not exists public.prod_paros (
  id               bigint generated by default as identity primary key,
  fecha            date not null,
  planta           text not null,
  proceso          text,
  familia          text,             -- FUNCIONAL | INDUCIDO | EXPLOTACION | AVERIA
  modo_perdida     text,
  equipo           text,
  descripcion      text,
  minutos          numeric not null default 0,
  tipo             text,             -- REAL | REFLEJADO (los indicadores de pérdidas usan los REFLEJADO)
  area_responsable text,
  responsable      text,
  origen           text not null default 'app',
  registrado_por   text,
  created_at       timestamptz not null default now()
);
create index if not exists prod_paros_fecha_idx on public.prod_paros (fecha desc, planta);

create table if not exists public.prod_plantas_activas (
  fecha    date primary key,
  plantas  text not null            -- 'TODAS (5)', 'MS+MBL+CEFI', ... (vacío = todas las que tengan registro)
);

create table if not exists public.prod_parametros (
  clave        text primary key,
  valor        jsonb not null,
  updated_at   timestamptz not null default now(),
  actualizado_por text
);

